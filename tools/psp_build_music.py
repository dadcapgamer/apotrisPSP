#!/usr/bin/env python3
"""Pack Apotris' music modules into one blob for the PSP port.

Modules are linked in whole and handed to libxmp from memory, so nothing is
read from the filesystem at runtime. The ordering matches the desktop backend:
the module files are sorted by name and numbered in one flat sequence, with
"MENU_" files forming the menu list and the rest the in-game list.

Outputs (all generated, none checked in):
    <outdir>/psp_music.bin        concatenated module files
    <outdir>/psp_music.s          .incbin wrapper for the blob
    <outdir>/psp_music_table.h    offset/length table plus the two song lists
"""

import argparse
import glob
import os
import sys

MODULE_SUFFIXES = (".it", ".mod", ".s3m", ".S3M", ".xm")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", default=".", help="repository root")
    parser.add_argument("--outdir", required=True)
    args = parser.parse_args()

    assets = os.path.join(args.root, "assets")
    paths = sorted(
        name
        for name in os.listdir(assets)
        if name.endswith(MODULE_SUFFIXES)
    )
    if not paths:
        raise SystemExit(f"no music modules found in {assets}")

    os.makedirs(args.outdir, exist_ok=True)

    blob = bytearray()
    table = []
    menu = []
    game = []
    for index, name in enumerate(paths):
        data = open(os.path.join(assets, name), "rb").read()
        table.append((len(blob), len(data), name))
        blob += data
        # libxmp reads the module header directly out of the blob, so keep
        # every entry 4-byte aligned.
        blob += b"\0" * (-len(blob) % 4)
        (menu if name.startswith("MENU_") else game).append(index)

    bin_path = os.path.join(args.outdir, "psp_music.bin")
    with open(bin_path, "wb") as out:
        out.write(blob)

    with open(os.path.join(args.outdir, "psp_music.s"), "w", encoding="utf-8") as out:
        out.write("/* Generated by tools/psp_build_music.py - do not edit */\n")
        out.write("\t.section\t.rodata.pspMusicData\n")
        out.write("\t.balign\t4\n")
        out.write("\t.global\tpspMusicData\n")
        out.write("pspMusicData:\n")
        out.write(f'\t.incbin\t"{bin_path}"\n')
        out.write("\t.size\tpspMusicData, . - pspMusicData\n")

    header = os.path.join(args.outdir, "psp_music_table.h")
    with open(header, "w", encoding="utf-8") as out:
        out.write("/* Generated by tools/psp_build_music.py - do not edit */\n")
        out.write("#pragma once\n\n")
        out.write("#include <cstdint>\n\n")
        out.write(f"#define PSP_MUSIC_COUNT {len(table)}\n\n")
        out.write("extern const uint8_t pspMusicData[];\n\n")
        out.write("struct PspMusicEntry {\n")
        out.write("    uint32_t offset; /* in bytes, into pspMusicData */\n")
        out.write("    uint32_t length; /* in bytes */\n")
        out.write("};\n\n")
        out.write("static const PspMusicEntry pspMusicTable[PSP_MUSIC_COUNT] = {\n")
        for offset, length, name in table:
            out.write(f"    {{{offset}, {length}}}, /* {name} */\n")
        out.write("};\n\n")
        out.write(f"#define PSP_MUSIC_MENU_LIST {{{', '.join(map(str, menu))}}}\n")
        out.write(f"#define PSP_MUSIC_GAME_LIST {{{', '.join(map(str, game))}}}\n")

    print(
        f"psp_build_music: {len(table)} modules, {len(blob) / 1024:.0f} KiB "
        f"({len(menu)} menu, {len(game)} in-game)",
        file=sys.stderr,
    )


if __name__ == "__main__":
    main()
