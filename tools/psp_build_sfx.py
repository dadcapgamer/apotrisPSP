#!/usr/bin/env python3
"""Pack Apotris' sound effects into one blob for the PSP port.

Every effect is downmixed to mono and resampled to a single rate so the PSP
mixer never has to care about per-effect formats. Storing at half the output
rate halves the resident size; the mixer interpolates on playback anyway
because sfxRate() needs arbitrary playback rates regardless.

Outputs (all generated, none checked in):
    <outdir>/psp_sfx.bin        concatenated mono s16 PCM
    <outdir>/psp_sfx.s          .incbin wrapper for the blob
    <outdir>/psp_sfx_table.h    offset/length table in SoundEffects order
"""

import argparse
import os
import re
import struct
import sys
import wave

SAMPLE_RATE = 22050


def read_sfx_paths(source_file):
    """Return SoundEffectPaths[] in SoundEffects enum order."""
    text = open(source_file, encoding="utf-8").read()
    body = re.search(r"SoundEffectPaths\[\]\s*=\s*\{(.*?)\}\s*;", text, re.S)
    if not body:
        raise SystemExit(f"could not find SoundEffectPaths[] in {source_file}")
    return re.findall(r'"([^"]+)"', body.group(1))


def decode_mono_s16(path):
    """Decode a 16-bit PCM wav to (samples, rate), downmixing to mono."""
    with wave.open(path) as w:
        if w.getsampwidth() != 2 or w.getcomptype() != "NONE":
            raise SystemExit(f"{path}: expected 16-bit PCM")
        channels = w.getnchannels()
        frames = w.readframes(w.getnframes())
        rate = w.getframerate()

    samples = memoryview(frames).cast("h")
    if channels == 1:
        return list(samples), rate
    if channels != 2:
        raise SystemExit(f"{path}: unsupported channel count {channels}")
    return [(samples[i] + samples[i + 1]) // 2 for i in range(0, len(samples), 2)], rate


def resample(samples, source_rate, target_rate):
    """Linear resample. Matches what the PSP mixer does at playback time."""
    if source_rate == target_rate or not samples:
        return samples

    count = max(1, round(len(samples) * target_rate / source_rate))
    step = len(samples) / count
    out = []
    for i in range(count):
        position = i * step
        index = int(position)
        if index + 1 >= len(samples):
            out.append(samples[-1])
            continue
        fraction = position - index
        a = samples[index]
        b = samples[index + 1]
        out.append(int(a + (b - a) * fraction))
    return out


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", default=".", help="repository root")
    parser.add_argument("--outdir", required=True)
    args = parser.parse_args()

    root = args.root
    paths = read_sfx_paths(os.path.join(root, "source", "audio_files.cpp"))
    os.makedirs(args.outdir, exist_ok=True)

    blob = bytearray()
    table = []
    for path in paths:
        samples, rate = decode_mono_s16(os.path.join(root, path))
        samples = resample(samples, rate, SAMPLE_RATE)
        table.append((len(blob) // 2, len(samples), os.path.basename(path)))
        blob += struct.pack(f"<{len(samples)}h", *samples)

    bin_path = os.path.join(args.outdir, "psp_sfx.bin")
    with open(bin_path, "wb") as out:
        out.write(blob)

    with open(os.path.join(args.outdir, "psp_sfx.s"), "w", encoding="utf-8") as out:
        out.write("/* Generated by tools/psp_build_sfx.py - do not edit */\n")
        out.write("\t.section\t.rodata.pspSfxSamples\n")
        out.write("\t.balign\t4\n")
        out.write("\t.global\tpspSfxSamples\n")
        out.write("pspSfxSamples:\n")
        out.write(f'\t.incbin\t"{bin_path}"\n')
        out.write("\t.size\tpspSfxSamples, . - pspSfxSamples\n")

    with open(os.path.join(args.outdir, "psp_sfx_table.h"), "w", encoding="utf-8") as out:
        out.write("/* Generated by tools/psp_build_sfx.py - do not edit */\n")
        out.write("#pragma once\n\n")
        out.write("#include <cstdint>\n\n")
        out.write(f"#define PSP_SFX_SAMPLE_RATE {SAMPLE_RATE}\n")
        out.write(f"#define PSP_SFX_TABLE_COUNT {len(table)}\n\n")
        out.write("extern const int16_t pspSfxSamples[];\n\n")
        out.write("struct PspSfxEntry {\n")
        out.write("    uint32_t offset; /* in samples, into pspSfxSamples */\n")
        out.write("    uint32_t length; /* in samples */\n")
        out.write("};\n\n")
        out.write("static const PspSfxEntry pspSfxTable[PSP_SFX_TABLE_COUNT] = {\n")
        for offset, length, name in table:
            out.write(f"    {{{offset}, {length}}}, /* {name} */\n")
        out.write("};\n")

    print(
        f"psp_build_sfx: {len(table)} effects, "
        f"{len(blob) / 1024:.0f} KiB at {SAMPLE_RATE} Hz mono",
        file=sys.stderr,
    )


if __name__ == "__main__":
    main()
